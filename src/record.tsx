import { ArrowUpRight } from "lucide-react";
import data from "./record-data.json";
import "./record.css";

/* The Record: every move Waves.Fund has made, newest first, each linked to its commit in the public code, so anyone
   can check what moved and when. It holds what was built and nothing about visitors. Generated by
   scripts/record.mjs from the public repo's history. */
const day = (d: string) => new Date(d + "T12:00:00Z").toLocaleDateString("en-US", { month: "short", day: "numeric", timeZone: "UTC" });
function Move({ m }: { m: { sha: string; date: string; move: string } }) {
  return (
    <li className="rc-move">
      <time className="rc-date" dateTime={m.date}>{day(m.date)}</time>
      <a className="rc-link" href={`${data.repo}/commit/${m.sha}`} target="_blank" rel="noreferrer">{m.move}<span className="sr-only"> (opens the commit on GitHub)</span></a>
    </li>
  );
}
export function TheRecord() {
  const moves = data.moves, first = moves[moves.length - 1];
  return (
    <section className="rc" aria-labelledby="rc-title">
      <p className="eyebrow">THE RECORD · {moves.length} MOVES</p>
      <h2 id="rc-title">Every Move, In The Open.</h2>
      <p className="rc-lede">Each move links to its commit in the public code.</p>
      <ol className="rc-list">{moves.slice(0, 8).map((m) => <Move key={m.sha} m={m} />)}</ol>
      {moves.length > 8 && (
        <details className="rc-all">
          <summary>Every Move Since {day(first.date)}</summary>
          <ol className="rc-list">{moves.slice(8).map((m) => <Move key={m.sha} m={m} />)}</ol>
        </details>
      )}
      <a className="text-button rc-repo" href={`${data.repo}/commits/main`} target="_blank" rel="noreferrer">Open The Public Code <ArrowUpRight size={16} /></a>
    </section>
  );
}
